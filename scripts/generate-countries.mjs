// Regenerates supabase/functions/_shared/domain/countries.ts from i18n-iso-countries (ISO 3166-1 alpha-2).
import { writeFileSync } from "node:fs";
import countries from "i18n-iso-countries";
import en from "i18n-iso-countries/langs/en.json" with { type: "json" };

countries.registerLocale(en);
const names = countries.getNames("en", { select: "official" });
const entries = Object.entries(names).sort((a, b) => a[1].localeCompare(b[1]));
const body = entries.map(([code, name]) => `  { code: ${JSON.stringify(code)}, name: ${JSON.stringify(name)} },`).join("\n");
writeFileSync(
  new URL("../supabase/functions/_shared/domain/countries.ts", import.meta.url),
  `// GENERATED by scripts/generate-countries.mjs from i18n-iso-countries. Do not edit by hand.\n` +
    `export interface Country {\n  code: string;\n  name: string;\n}\n\n` +
    `export const COUNTRIES: Country[] = [\n${body}\n];\n\n` +
    `const CODES = new Set(COUNTRIES.map((c) => c.code));\n\n` +
    `export function isIsoCountry(code: string | null | undefined): boolean {\n  return !!code && CODES.has(code.toUpperCase());\n}\n\n` +
    `export function countryName(code: string | null | undefined): string {\n  return COUNTRIES.find((c) => c.code === code)?.name ?? code ?? "";\n}\n`,
);
console.log(`Wrote ${entries.length} countries`);
